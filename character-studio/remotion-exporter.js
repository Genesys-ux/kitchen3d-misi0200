  function sanitizeComponentName(raw) {
    const clean = (raw || 'CustomCharacter')
      .replace(/[^a-zA-Z0-9\s_]/g, ' ')
      .trim()
      .split(/[\s_]+/)
      .filter(Boolean)
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join('');
    let out = clean || 'CustomCharacter';
    if (/^[0-9]/.test(out)) out = 'Char' + out;
    return out;
  }

  function convertFnToTS(entry) {
    const src = entry.fn.toString();
    const firstBrace = src.indexOf('{');
    if (firstBrace === -1) return entry.tsHeader + '\n}';
    const body = src.slice(firstBrace + 1);
    // Dedent 2 spaces cleanly so exported TSX has crisp top-level indentation
    const lines = body.split('\n').map((line) => (line.startsWith('  ') ? line.slice(2) : line));
    return entry.tsHeader + lines.join('\n');
  }

  function buildRendererCoreTS() {
    if (!global.CharacterEngine || !global.CharacterEngine.getExportableCore) {
      throw new Error('CharacterEngine.getExportableCore() tidak ditemukan.');
    }
    const entries = global.CharacterEngine.getExportableCore();
    return entries.map(convertFnToTS).join('\n\n');
  }

